const shuffle = (arr) => arr.sort(() => Math.random() - 0.5);

const handler = async (m, { conn }) => {
  const chatId = m.chat;
  if (!global.gameKora) global.gameKora = {};
  
  if (global.gameKora[chatId]?.current) {
    return await conn.sendMessage(chatId, {
      text: global.gameKora[chatId].current.caption,
      contextInfo: context(m.sender)
    }, { quoted: m });
  }

  try {
    await m.react('⚽');
    const questionItem = footballQuestions[Math.floor(Math.random() * footballQuestions.length)];
    const opts = shuffle([...questionItem.opts]);
    
    const caption = `❐═━━━═╊⊰🩸⊱╉═━━━═❐\n*⚽ ┇ مسابقة أسئلة كرة القدم الرياضية ┇ ⚽*\n\n*السؤال:* ${questionItem.q}\n\n1. ≺ ${opts[0]} ≺\n2. ≺ ${opts[1]} ≺\n3. ≺ ${opts[2]} ≺\n4. ≺ ${opts[3]} ≺\n\n⏳ الوقت: 60 ثانية\n🪙 الجائزة: 500xp + 10 كوكيز\n\n⚠️ *ملاحظة:* يجب الرد (ريبلاي) على هذه الرسالة بالإجابة لكي تُحتسب!\n❐═━━━═╊⊰🩸⊱╉═━━━═❐`;
    
    const msg = await conn.sendMessage(chatId, {
      text: caption,
      contextInfo: context(m.sender)
    }, { quoted: m });
    
    global.gameKora[chatId] = {
      current: {
        answer: questionItem.a.toLowerCase().trim(),
        opts: opts.map(o => o.toLowerCase().trim()),
        caption,
        id: msg.key.id,
        timer: setTimeout(async () => {
          if (global.gameKora[chatId]?.current) {
            const ans = global.gameKora[chatId].current.answer;
            global.gameKora[chatId] = null; 
            await conn.sendMessage(chatId, { 
              text: `❐═━━━═╊⊰🩸⊱╉═━━━═❐\n⏰ *الوقت انتهى!*\nلم يتمكن أحد من الإجابة الرياضية الصحيحة.\n💡 الإجابة الصحيحة هي: *${ans}*\n❐═━━━═╊⊰🩸⊱╉═━━━═❐`,
              contextInfo: context(m.sender)
            });
          }
        }, 60000)
      }
    };

  } catch (e) {
    console.error(e);
    conn.reply(m.chat, '❌ حدث خطأ فني أثناء تشغيل لعبة كرة القدم.', m);
  }
};

handler.before = async (m, { conn }) => {
  const g = global.gameKora?.[m.chat];
  if (!g?.current) return false;
  
  const cur = g.current;
  
  const isReply = m.quoted ? m.quoted.id : null;
  if (!isReply || isReply !== cur.id) return false;
  
  if (!m.text) return false;
  const answer = m.text.toLowerCase().trim();

  if (answer === cur.answer) {
    clearTimeout(cur.timer);
    global.gameKora[m.chat] = null; 

    if (global.db?.data?.users?.[m.sender]) {
      global.db.data.users[m.sender].xp = (global.db.data.users[m.sender].xp || 0) + 500;
      global.db.data.users[m.sender].cookies = (global.db.data.users[m.sender].cookies || 0) + 10;
    }
    
    await conn.sendMessage(m.chat, {
      text: `❐═━━━═╊⊰🩸⊱╉═━━━═❐\n🎉 *إجابة صحيحة وممتازة كفوو! 🥇*\n👤 الفائز: @${m.sender.split('@')[0]}\n💡 الجواب الصحيح هو: *${m.text}*\n💰 الجائزة: +500xp 🪙 | +10 كوكيز 🍪\n❐═━━━═╊⊰🩸⊱╉═━━━═❐`,
      mentions: [m.sender],
      contextInfo: context(m.sender)
    }, { quoted: m });
    await m.react('✅');
  } else {
    if (cur.opts.includes(answer)) {
      await conn.sendMessage(m.chat, { 
         text: "❌ إجابة خاطئة! حاول مجدداً وركز في السؤال.",
         contextInfo: context(m.sender)
      }, { quoted: m });
      await m.react('❌');
    }
  }
  return true;
};

