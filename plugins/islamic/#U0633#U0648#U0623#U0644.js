const handler = async (m, { conn }) => {
  global.quiz = global.quiz || {}

  // التحقق من عدم وجود سؤال معلق حالياً
  if (global.quiz[m.chat]) {
    return await conn.sendMessage(m.chat, { text: "❌ هناك سؤال قائم بالفعل في هذه المجموعة! انتظر حتى ينتهي أو أجب عليه." }, { quoted: m })
  }

  const random = questions[Math.floor(Math.random() * questions.length)]

  // إرسال السؤال
  const sentMsg = await conn.sendMessage(m.chat, {
    text: `🕌 *مسابقة دينية وثقافية*

❓ *السؤال:*
${random.q}

⚠️ *ملاحظة:* يجب عليك الرد (ريبلاي) على هذه الرسالة بالإجابة الصحيحة لكي تُحتسب!
⏳ لديك *60 ثانية*`
  }, { quoted: m })

  // حفظ تفاصيل السؤال الحالي في الذاكرة
  global.quiz[m.chat] = {
    answer: random.a.trim().toLowerCase(),
    msgId: sentMsg.key.id,
    active: true,
    time: setTimeout(async () => {
      if (global.quiz[m.chat]) {
        // انتهاء الوقت دون إجابة -> البوت يعلن الإجابة ويقفل المسابقة
        await conn.sendMessage(m.chat, {
          text: `⏳ *انتهى الوقت!* \n\nلم يتمكن أحد من الإجابة في الوقت المحدد (60 ثانية).\n💡 الإجابة الصحيحة هي: *${random.a}*\n\n🏁 *انتهت الجولة.*`
        })
        delete global.quiz[m.chat] // إخلاء الذاكرة لتمكين بدء اللعب من جديد لاحقاً
      }
    }, 60000) // 60 ثانية
  }
}

handler.before = async function (m) {
  global.quiz = global.quiz || {}

  if (!global.quiz[m.chat] || !global.quiz[m.chat].active) return false
  if (!m.text) return false 

  const currentQuiz = global.quiz[m.chat]
  const isReply = m.quoted ? m.quoted.id : null

  // شرط الريبلاي على رسالة البوت حصراً
  if (!isReply || isReply !== currentQuiz.msgId) return false

  const userAnswer = m.text.trim().toLowerCase()

  // إذا كانت الإجابة صحيحة
  if (userAnswer === currentQuiz.answer) {
    clearTimeout(currentQuiz.time) // إيقاف تايمر الـ 60 ثانية لكي لا يشتغل
    delete global.quiz[m.chat]     // قفل اللعبة

    await m.reply(`🎉 *إجابة صحيحة وممتازة!* \n\n👤 أحسنت: @${m.sender.split('@')[0]}\n💡 الجواب هو: *${m.text}*\n\n🏁 *انتهت الجولة.*`, null, {
      mentions: [m.sender]
    })
  }
  
  return false
}

handler.usage = ["سؤال"];
handler.command = ["سؤال"]
handler.category = "islamic"

export default handler
