add('تباين_اللونين', 'حساب نسبة التباين WCAG بين لونين (مثال: .تباين_اللونين #FFFFFF | #0F172A)', async (m, ctx) => {
  const [c1, c2] = splitArgsPipe(ctx);
  const lum = (hex) => {
    const rgb = hexToRgb(hex || '#FFFFFF') || [255, 255, 255];
    const [r, g, b] = rgb.map((v) => {
      const s = v / 255;
      return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
    });
    return 0.2126 * r + 0.7152 * g + 0.0722 * b;
  };
  const l1 = lum(c1 || '#FFFFFF'), l2 = lum(c2 || '#0F172A');
  const ratio = (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
  await sendInteractiveCard(m, ctx, {
    title: 'فحص التباين البصري WCAG',
    badge: '👁️',
    fields: [
      { icon: '🎯', label: 'نسبة التباين', value: `${ratio.toFixed(2)} : 1` },
      { icon: '✅', label: 'التقييم', value: ratio >= 7 ? 'AAA ممتاز للنصوص الدقيقة 🌟' : ratio >= 4.5 ? 'AA مقبول ومريح للقراءة ✅' : 'ضعيف التباين — غيّر أحد اللونين ⚠️' }
    ],
    theme: 'royal'
  });
}, ['تباين_اللونين <#لون1> | <#لون2>'], 'tools');

