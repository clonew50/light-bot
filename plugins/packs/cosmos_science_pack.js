const COMPLEMENT_DNA = { A: 'T', T: 'A', C: 'G', G: 'C' };
const CODON_TABLE = {
  ATG: 'Met (بدء)', TGG: 'Trp', TTT: 'Phe', TTC: 'Phe', GCT: 'Ala', GCC: 'Ala',
  GGA: 'Gly', GGC: 'Gly', GAA: 'Glu', GAG: 'Glu', AAA: 'Lys', AAG: 'Lys',
  TAA: 'STOP (توقف)', TAG: 'STOP (توقف)', TGA: 'STOP (توقف)'
};

add('مكمل_dna', 'توليد الشريط المكمل لـ DNA (مثال: .مكمل_dna ATGCGTAC)', async (m, ctx) => {
  const seq = (String(ctx.text || 'ATGCGTAC').toUpperCase().match(/[ATCG]/g) || []).join('') || 'ATGCGTAC';
  const comp = seq.split('').map((b) => COMPLEMENT_DNA[b] || 'N').join('');
  await sendInteractiveCard(m, ctx, {
    title: 'تطابق قواعد DNA',
    badge: '🧬',
    fields: [
      { icon: '5️⃣', label: 'الشريط الأصلي', value: seq },
      { icon: '3️⃣', label: 'الشريط المكمل', value: comp }
    ],
    theme: 'emerald',
    buttons: [makeCopyButton('📋 نسخ المكمل', comp)]
  });
}, ['مكمل_dna <ATCG...>'], 'tools');

add('نسبة_gc_الوراثية', 'حساب نسبة قواعد الجوانين والسيتوزين (GC Content) التي تحدد ثبات DNA', async (m, ctx) => {
  const seq = (String(ctx.text || 'ATGCGCCGTTA').toUpperCase().match(/[ATCG]/g) || []).join('') || 'ATGCGCCGTTA';
  const gc = seq.split('').filter((b) => b === 'G' || b === 'C').length;
  const pct = Math.round((gc / seq.length) * 100);
  await sendInteractiveCard(m, ctx, {
    title: 'تحليل نسبة GC الوراثية',
    badge: '🧪',
    fields: [
      { icon: '🧬', label: 'التسلسل', value: `${seq} (${seq.length} قاعدة)` },
      { icon: '📊', label: 'نسبة GC', value: progressBar(pct, 100, 10) }
    ],
    theme: 'emerald'
  });
}, ['نسبة_gc_الوراثية <ATCG...>'], 'tools');

add('ترجمة_كودون_dna', 'ترجمة أول كودونات ثلاثية من سلسلة DNA إلى أحماض أمينية', async (m, ctx) => {
  const seq = (String(ctx.text || 'ATGGCTGAA').toUpperCase().match(/[ATCG]/g) || []).join('') || 'ATGGCTGAA';
  const codons = seq.match(/.{1,3}/g) || [];
  const translated = codons.map((c) => `${c}→${CODON_TABLE[c] || 'حمض أميني قياسي'}`).join(' | ');
  await sendInteractiveCard(m, ctx, { title: 'مختبر ترجمة الكودونات', badge: '🧬', body: translated, theme: 'emerald' });
}, ['ترجمة_كودون_dna <ATG...>'], 'tools');

