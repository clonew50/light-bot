const handlers = [];
const add = (cmd, desc, fn, usage) => {
  const triggers = Array.isArray(cmd) ? cmd : [cmd];
  const h = async (m, ctx) => {
    try { await fn(m, ctx); }
    catch (e) { await m.reply('❌ ' + (e?.message || e)); }
  };
  h.command = triggers;
  h.usage = usage || [triggers[0]];
  h.description = desc;
  h.category = 'games';
  h.usePrefix = true;
  handlers.push(h);
};

function ensureUser(sender) {
  if (!global.db) global.db = { users: {}, groups: {} };
  if (!global.db.users) global.db.users = {};
  if (!sender || !String(sender).includes('@')) return null;
  if (!global.db.users[sender]) global.db.users[sender] = {};
  return global.db.users[sender];
}

function addReward(sender, coins = 0, xp = 0) {
  const u = ensureUser(sender);
  if (!u) return { coins: 0, xp: 0 };
  const nextCoins = (Number(u.money || u.coins || 0) || 0) + coins;
  const nextXp = (Number(u.exp || u.xp || 0) || 0) + xp;
  if (nextCoins > 0) u.money = nextCoins;
  if (nextXp > 0) u.exp = nextXp;
  return { coins: nextCoins, xp: nextXp };
}

function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

