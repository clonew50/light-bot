for (const [cmd, desc] of COMMUNITY_CARDS) {
  add(cmd, desc, async (m, ctx) => {
    const t = String(ctx.text || '').trim();
    if (cmd === 'استطلاع_مسابقة_الشلة') {
      return sendInteractivePoll(m, ctx, { name: 'أي مسابقة نلعبها الآن مع الشلة؟', values: ['🔤 لعبة الحروف', '🧠 أسئلة ثقافية', '🎭 حقيقتان وكذبة', '🎨 سباق الإيموجي'], selectableCount: 1 });
    }
    if (cmd === 'تصويت_الفائز_بالمناظرة') {
      return sendInteractivePoll(m, ctx, { name: t || 'من أقنعكم أكثر في مناظرة اليوم؟', values: ['🔴 الفريق المؤيد', '🔵 الفريق المعارض', '⚖️ تعادل عادل'], selectableCount: 1 });
    }
    if (cmd === 'استطلاع_وقت_السهرة') {
      return sendInteractivePoll(m, ctx, { name: 'ما التوقيت الأنسب لبدء سهرة المجموعة؟', values: ['🕘 9 مساءً', '🕙 10 مساءً', '🕚 11 مساءً', '🕛 منتصف الليل'], selectableCount: 1 });
    }
    if (cmd === 'ودجت_لوحة_الشرف') {
      const html = makeSimpleHtmlWidget('🏆 لوحة شرف المجتمع', '#eab308', [
        ['الفعالية', 'ساحة التفاعل الجماعي'],
        ['روح المجموعة', 'الاحترام + المرح النظيف'],
        ['أمر السهرة', '.كسر_الجليد / .محكمة_المجموعة'],
        ['النجم الحالي', String(m.sender).split('@')[0]]
      ]);
      return sendInteractiveWidget(m, ctx, { title: 'لوحة شرف المجتمع', html, fallbackText: 'لوحة شرف المجموعة جاهزة!' });
    }
    if (cmd === 'مؤشر_النشاط_الاجتماعي') {
      const u = ensureDbUser(m.sender);
      return sendInteractiveCard(m, ctx, { title: 'مؤشر تفاعلك الاجتماعي', badge: '📊', fields: [{ icon: '⭐', label: 'الخبرة', value: `${u.exp} XP` }, { icon: '🪙', label: 'الرصيد', value: `${u.money} 🪙` }], theme: 'royal' });
    }
    if (cmd === 'قائمة_الأبطال') {
      const top = Object.entries(global.db?.users || {}).sort((a, b) => (b[1]?.exp || 0) - (a[1]?.exp || 0)).slice(0, 5);
      const body = top.length ? top.map(([id, v], i) => `${i + 1}. 👑 ${id.split('@')[0]} — ${v.exp || 0} XP`).join('\n') : 'لا توجد سجلات بعد!';
      return sendInteractiveCard(m, ctx, { title: 'قائمة أبطال المجموعة', badge: '🏆', body, theme: 'royal' });
    }

    const body = QUICK_GAME_PROMPTS[cmd] || (t
      ? `✨ *تم التطبيق على (${t}):*\n${desc} — بكل تقدير وروح طيبة!`
      : `✨ ${desc}\n💡 اذكر اسم الشخص بعد الأمر لتخصيص البطاقة له!`);
    await sendInteractiveCard(m, ctx, {
      title: cmd.replace(/_/g, ' '),
      badge: '🎉',
      body,
      theme: 'royal',
      buttons: [makeQuickButton('🎲 كسر الجليد', 'كسر_الجليد')]
    });
  }, [cmd], cmd.startsWith('استطلاع_') || cmd.startsWith('تصويت_') || cmd.startsWith('ودجت_') ? 'native' : 'group');
}

