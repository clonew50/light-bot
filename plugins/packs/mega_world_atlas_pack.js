const CITY_MAP = new Map(CITIES.map((c) => [c[0].toLowerCase(), { id: c[0], name: c[1], lat: c[2], lng: c[3], tz: c[4] }]));

function haversineKm(lat1, lon1, lat2, lon2) {
  const R = 6371;
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

async function execute(m, ctx) {
  const cmd = getCmdKey(m, ctx);

  if (cmd.startsWith('مسافة_مدن_')) {
    const rest = cmd.slice('مسافة_مدن_'.length);
    const sep = rest.indexOf('_الى_');
    const c1 = CITY_MAP.get(rest.slice(0, sep));
    const c2 = CITY_MAP.get(rest.slice(sep + 5));
    if (!c1 || !c2) return;
    const km = haversineKm(c1.lat, c1.lng, c2.lat, c2.lng);
    const flightHr = (km / 850 + 0.45).toFixed(1);
    const tzDiff = c2.tz - c1.tz;
    return replyCard(m, ctx, '✈️', `المسافة بين ${c1.name} و ${c2.name}`, [
      `📏 *المسافة الجوية المباشرة:* ${Math.round(km).toLocaleString()} كم (${Math.round(km * 0.621371).toLocaleString()} ميل)`,
      `🛫 *زمن الطيران التقديري:* ~${flightHr} ساعة`,
      `🕒 *فرق التوقيت:* ${tzDiff >= 0 ? '+' : ''}${tzDiff} ساعة`
    ], 'أطلس العالم');
  }

  if (cmd.startsWith('معلومة_بلد_') || cmd.startsWith('توقيت_بلد_') || cmd.startsWith('علم_دولة_')) {
    const idx = parseInt(cmd.split('_').pop(), 10);
    const c = CITIES[(idx - 1) % CITIES.length];
    const nowUtc = Date.now() + c[4] * 3600000;
    const dt = new Date(nowUtc).toISOString().slice(11, 16);
    return replyCard(m, ctx, '🌍', `البطاقة الجغرافية #${idx}: ${c[1]}`, [
      `📍 *الإحداثيات:* ${c[2].toFixed(3)}, ${c[3].toFixed(3)}`,
      `🕒 *التوقيت المحلي الآن:* ${dt} (UTC${c[4] >= 0 ? '+' : ''}${c[4]})`
    ]);
  }

  if (cmd.startsWith('موسوعة_حدث_')) {
    const idx = parseInt(cmd.slice('موسوعة_حدث_'.length), 10);
    const eras = ['العصر القديم', 'العصر الذهبي الإسلامي', 'عصر النهضة', 'الثورة الصناعية', 'عصر الفضاء والرقمية'];
    const c = CITIES[(idx * 7) % CITIES.length];
    return replyCard(m, ctx, '🏛️', `سجل الموسوعة التاريخية #${idx}`, [
      `🕰️ *الحقبة:* ${eras[idx % eras.length]} | *المركز الحضاري:* ${c[1]}`,
      `📜 *الدرس التاريخي #${idx}:* توثيق مسارات العلوم والملاحة والتبادل التجاري عبر ${c[1]}.`
    ]);
  }
}

