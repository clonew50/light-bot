for (const [cmd, desc] of FIELD_MANUAL) {
  add(cmd, desc, async (m, ctx) => {
    if (cmd === 'تصويت_بيئة_البقاء') {
      return sendInteractivePoll(m, ctx, {
        name: 'أي بيئة بقاء تجدها الأكثر تحدياً وإثارة؟',
        values: ['🏜️ الصحراء الكبرى', '🧊 القطب المتجمد', '🌴 الغابة الاستوائية', '🏝️ الجزيرة المهجورة'],
        selectableCount: 1
      });
    }
    if (cmd === 'ودجت_بوصلة_النجاة') {
      const { exp } = ensureExpedition(m.sender);
      const html = makeSimpleHtmlWidget('🧭 بوصلة النجاة الميدانية', '#10b981', [
        ['البيئة الحالية', exp.biome],
        ['اليوم / المسافة', `${exp.day} | ${exp.distanceKm} كم`],
        ['الصحة / الماء', `${exp.health}% | ${exp.hydration}%`],
        ['القاعدة الذهبية', 'توقف، فكّر، راقب، خطط']
      ]);
      return sendInteractiveWidget(m, ctx, { title: 'بوصلة النجاة', html, fallbackText: `${exp.biome} — ${exp.distanceKm} كم` });
    }
    await sendInteractiveCard(m, ctx, { title: cmd.replace(/_/g, ' '), badge: '🧭', body: desc, theme: 'emerald' });
  }, [cmd], cmd.startsWith('تصويت_') || cmd.startsWith('ودجت_') ? 'native' : 'tools');
}

