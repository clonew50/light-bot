const handlers = [];
const add = (cmd, desc, fn, usage, cat = 'games') => {
  const triggers = Array.isArray(cmd) ? cmd : [cmd];
  const h = async (m, ctx) => {
    try { await fn(m, ctx); }
    catch (e) { await m.reply('❌ ' + (e?.message || e)); }
  };
  h.command = triggers;
  h.usage = usage || [triggers[0]];
  h.description = desc;
  h.category = cat;
  h.usePrefix = true;
  handlers.push(h);
};

function ensureExpedition(sender, biome = 'الصحراء الكبرى 🏜️') {
  const u = ensureDbUser(sender);
  if (!u.expedition) {
    u.expedition = {
      biome,
      day: 1,
      health: 100,
      hydration: 85,
      warmth: 80,
      fireLit: false,
      shelter: false,
      supplies: 4,
      distanceKm: 0
    };
  }
  return { u, exp: u.expedition };
}

